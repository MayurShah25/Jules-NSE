class ScalpingStrategy:
    def __init__(self, broker: BrokerAPI):
        self.broker = broker
        self.risk_manager = RiskManager(broker)
        self.in_position = False
        self.current_position = None  # 'CE' or 'PE'
        self.entry_price = 0.0
        self.current_sl = 0.0
        self.option_symbol = ""
        self.last_heartbeat_time = datetime.now()
        self.last_pnl_heartbeat_time = datetime.now()
        self.last_fetch_time = None
        self.cached_market_data = None
        self.daily_realized_pnl = 0.0

    def fetch_and_calculate_indicators(self):
        """Fetches data and calculates Rolling High/Low, VWAP, EMA, ADX."""
        # Rate Limiting: Only fetch historical data once every 60 seconds
        now = datetime.now()
        if self.last_fetch_time and (now - self.last_fetch_time).total_seconds() < 60:
            if self.cached_market_data:
                try:
                    # Update only the current close price (LTP) for precise breakout detection
                    self.cached_market_data['close'] = self.broker.get_ltp(SYMBOL)
                except Exception as e:
                    logger.warning(f"Error updating live index price: {e}")
                return self.cached_market_data
            return None # Strict rate limit enforcement if cache is empty

        df = self.broker.get_historical_data(SYMBOL, TIMEFRAME)

        # Always update the fetch time so we don't spam the API on failure
        self.last_fetch_time = now

        if df is None or len(df) < 50:
            return None

        # Assuming 'df' has columns: datetime, open, high, low, close, volume
        # 1. Rolling 30-Minute High / Low (30 candles on 1min chart)
        # Exclude the current live, unclosed candle (-1)
        # Ensure we don't mix previous day's data during the first 30 minutes of a gap open
        today_date = datetime.now().date()
        today_mask = df.index.date == today_date
        today_df = df[today_mask]

        if len(today_df) > 1:
            # We have at least some closed candles today
            rolling_data = today_df.iloc[-31:-1]
            rolling_high = rolling_data['high'].max()
            rolling_low = rolling_data['low'].min()
        else:
            # Not enough data for today yet (e.g. first candle of the day is forming)
            # Fallback to previous 30 candles, though trades are unlikely this early
            rolling_data = df.iloc[-31:-1]
            rolling_high = rolling_data['high'].max()
            rolling_low = rolling_data['low'].min()

        # 2. Indicators (using ta)
        df[f'EMA_{EMA_PERIOD}'] = ta.trend.EMAIndicator(close=df['close'], window=EMA_PERIOD).ema_indicator()

        adx_ind = ta.trend.ADXIndicator(high=df['high'], low=df['low'], close=df['close'], window=ADX_PERIOD)
        df[f'ADX_{ADX_PERIOD}'] = adx_ind.adx()
        df['ADX_Slope'] = df[f'ADX_{ADX_PERIOD}'].diff()

        df[f'RSI_{RSI_PERIOD}'] = ta.momentum.RSIIndicator(close=df['close'], window=RSI_PERIOD).rsi()

        # Simplified Intraday VWAP / Fallback
        # We must calculate VWAP only on today's data slice
        df['Typical_Price'] = (df['high'] + df['low'] + df['close']) / 3

        # If the broker returns 0 volume for the index, fallback to cumulative typical price average
        if 'volume' not in df.columns or df.loc[today_mask, 'volume'].sum() == 0:
            df.loc[today_mask, 'VWAP_D'] = df.loc[today_mask, 'Typical_Price'].expanding().mean()
        else:
            df.loc[today_mask, 'Vol_x_Typ'] = df.loc[today_mask, 'volume'] * df.loc[today_mask, 'Typical_Price']
            df.loc[today_mask, 'Cum_Vol'] = df.loc[today_mask, 'volume'].cumsum()
            df.loc[today_mask, 'Cum_Vol_x_Typ'] = df.loc[today_mask, 'Vol_x_Typ'].cumsum()
            df.loc[today_mask, 'VWAP_D'] = df.loc[today_mask, 'Cum_Vol_x_Typ'] / df.loc[today_mask, 'Cum_Vol']

        latest_data = df.iloc[-1]

        # Ensure ADX is populated (requires 28 periods to stabilize)
        if pd.isna(latest_data[f'ADX_{ADX_PERIOD}']) or pd.isna(latest_data['ADX_Slope']) or pd.isna(latest_data[f'RSI_{RSI_PERIOD}']):
            return None

        self.cached_market_data = {
            'timestamp': df.index[-1],
            'close': latest_data['close'],
            'open': latest_data['open'],
            'high': latest_data['high'],
            'low': latest_data['low'],
            'rolling_high': rolling_high,
            'rolling_low': rolling_low,
            'ema': latest_data[f'EMA_{EMA_PERIOD}'],
            'adx': latest_data[f'ADX_{ADX_PERIOD}'],
            'adx_slope': latest_data['ADX_Slope'],
            'rsi': latest_data[f'RSI_{RSI_PERIOD}'],
            'vwap': latest_data['VWAP_D']
        }
        return self.cached_market_data



    def execute_trade(self, opt_type, spot_price, adx_value):
        """Executes the entry order and sets dynamic initial SL."""
        strike = self.get_atm_strike(spot_price)
        self.option_symbol, dynamic_lot_size = self.get_option_symbol(strike, opt_type)

        if not self.option_symbol or not dynamic_lot_size:
            logger.error("Trade Aborted: Could not determine valid option symbol or lot size from broker.")
            return

        # Dynamic Quantity Calculation based on Live Balance (Max 10 Lots)
        live_balance = self.broker.get_balance()
        # Use 95% of available capital
        max_investment = live_balance * 0.95

        # Estimate premium using ~0.5 delta assumption for ATM (just for initial sizing if fetching fails)
        estimated_premium = (spot_price * 0.005)

        # Try to get the actual live premium first to size perfectly
        try:
            live_premium = self.broker.get_ltp(self.option_symbol)
            if live_premium > 0:
                estimated_premium = live_premium
        except Exception:
            pass

        calculated_lots = int(max_investment / (estimated_premium * dynamic_lot_size))
        calculated_lots = min(calculated_lots, 10) # Cap at 10 lots max

        if calculated_lots <= 0:
            logger.error(f"Trade Aborted: Insufficient funds to buy even 1 lot. Balance: {live_balance}")
            return

        trade_qty = calculated_lots * dynamic_lot_size

        # Place Market Order
        order_id = self.broker.place_order(self.option_symbol, "BUY", trade_qty)

        if not order_id:
            logger.error("Trade Aborted: Order placement failed via broker API.")
            return

        # WE ARE NOW IN A LIVE POSITION
        self.in_position = True
        self.current_position = opt_type
        self.current_qty = trade_qty

        try:
            # Fetch Entry Price
            self.entry_price = self.broker.get_ltp(self.option_symbol)
        except Exception as e:
            logger.error(f"Failed to fetch exact entry price after fill - {e}. Falling back to estimated premium.")
            # DO NOT ABORT OR SET IN_POSITION TO FALSE! We already bought it!
            self.entry_price = estimated_premium

        # Dynamic Risk Allocation based on trend strength
        if adx_value >= 30:
            self.trade_sl_pct = 0.08
            self.trade_target_pct = 0.20
            self.trade_trailing_pct = 1.0
            logger.info("Very Strong Trend Detected. Engaging Max Profitability settings.")
        elif adx_value >= ADX_THRESHOLD:
            self.trade_sl_pct = 1.0
            self.trade_target_pct = 0.10
            self.trade_trailing_pct = 0.03
            logger.info("Moderate Trend Detected. Engaging Balanced Scalp settings.")
        else:
            self.trade_sl_pct = 0.03
            self.trade_target_pct = 0.06
            self.trade_trailing_pct = 0.02
            logger.info("Sideways Chop Detected. Engaging tight hit-and-run scalping parameters.")

        # Calculate & System Place SL
        self.current_sl = self.risk_manager.calculate_sl(self.entry_price, self.trade_sl_pct)
        # In reality, place a Stop Loss Market (SL-M) order here with the broker

        self.in_position = True
        self.current_position = opt_type
        self.max_opt_price_seen = self.entry_price
        self.target_reached = False
        self.breakeven_reached = False
        self.last_pnl_heartbeat_time = datetime.now()

        logger.info(f"Entered {opt_type} at {self.entry_price}. Initial SL: {self.current_sl}")

    def exit_trade(self, reason):
        """Exits current position."""
        trade_qty = getattr(self, 'current_qty', LOT_SIZE)

        # If we are LONG (CE), we must SELL to exit. If SHORT (PE), we must BUY to cover.
        exit_direction = "SELL" if self.current_position == "CE" else "BUY"
        self.broker.place_order(self.option_symbol, exit_direction, trade_qty)

        try:
            exit_price = self.broker.get_ltp(self.option_symbol)
        except Exception:
            # Fallback to current SL if fetch fails during exit
            exit_price = self.current_sl

        realized_pnl = (exit_price - self.entry_price) * trade_qty
        self.daily_realized_pnl += realized_pnl

        logger.info(f"Exited position {self.current_position} at {exit_price:.2f}. Reason: {reason}")
        logger.info(f"Trade PNL: ₹{realized_pnl:.2f} | Total Daily PNL: ₹{self.daily_realized_pnl:.2f}")

        self.in_position = False
        self.current_position = None
        self.entry_price = 0.0
        self.current_sl = 0.0

    def manage_open_position(self):
        """Manages Trailing Take Profit, Breakeven SL, and Stop Loss hits."""
        try:
            current_opt_price = self.broker.get_ltp(self.option_symbol)
        except Exception as e:
            logger.warning(f"Error checking open position price: {e}")
            return

        if self.current_position == "CE":
            if current_opt_price > self.max_opt_price_seen:
                self.max_opt_price_seen = current_opt_price
        else:
            if current_opt_price < self.max_opt_price_seen:
                self.max_opt_price_seen = current_opt_price

        trade_qty = getattr(self, 'current_qty', LOT_SIZE)
        if self.current_position == "CE":
            current_floating_pnl = (current_opt_price - self.entry_price) * trade_qty
        else:
            current_floating_pnl = (self.entry_price - current_opt_price) * trade_qty

        # Live PNL Logging
        now = datetime.now()
        if (now - self.last_pnl_heartbeat_time).total_seconds() >= 30: # Log every 30 seconds
            logger.info(f"[LIVE PNL] {self.option_symbol} | LTP: {current_opt_price:.2f} | PNL: ₹{current_floating_pnl:.2f} | SL: {self.current_sl:.2f}")
            self.last_pnl_heartbeat_time = now

        # 0. Floating Kill Switch Hit
        if self.risk_manager.check_kill_switch(current_floating_pnl=current_floating_pnl):
            self.exit_trade("Kill Switch Hit")
            return

        # 1. Check SL / TTP Hit
        if self.current_position == "CE" and current_opt_price <= self.current_sl:
            reason = "Trailing Take Profit Hit" if self.target_reached else ("Break Even Hit" if self.breakeven_reached else "Stop Loss Hit")
            self.exit_trade(reason)
            return
        elif self.current_position == "PE" and current_opt_price >= self.current_sl:
            reason = "Trailing Take Profit Hit" if self.target_reached else ("Break Even Hit" if self.breakeven_reached else "Stop Loss Hit")
            self.exit_trade(reason)
            return

        if self.current_position == "CE":
            points_gained = current_opt_price - self.entry_price
        else:
            points_gained = self.entry_price - current_opt_price

        # 2. Update Trailing Take Profit (Target Reached)
        if points_gained >= self.trade_target_points:
            if not self.target_reached:
                logger.info(f"Target Reached! Activating Trailing Take Profit.")
                self.target_reached = True

            if self.current_position == "CE":
                new_sl = self.max_opt_price_seen - self.trade_trailing_points
                if new_sl > self.current_sl:
                    self.current_sl = new_sl
            else:
                new_sl = self.max_opt_price_seen + self.trade_trailing_points
                if new_sl < self.current_sl:
                    self.current_sl = new_sl

        # 3. Update to Break Even (1:1 RR Reached)
        elif points_gained >= self.trade_sl_points and not self.target_reached and not self.breakeven_reached:
            self.breakeven_reached = True
            if self.current_position == "CE":
                self.current_sl = self.entry_price + (TICK_SIZE * 5) # Slightly above entry to cover fees
            else:
                self.current_sl = self.entry_price - (TICK_SIZE * 5)
            logger.info(f"1:1 R:R Reached. Moving SL to Break Even: {self.current_sl:.2f}")

        # 4. Continuous Step Trailing (Between Break-Even and Target)
        elif self.breakeven_reached and not self.target_reached:
            if self.current_position == "CE":
                new_sl = self.max_opt_price_seen - self.trade_trailing_points
                if new_sl > self.current_sl:
                    self.current_sl = new_sl
            else:
                new_sl = self.max_opt_price_seen + self.trade_trailing_points
                if new_sl < self.current_sl:
                    self.current_sl = new_sl

    def run_cycle(self):
        """Main strategy loop executed every tick/candle."""
        # Sync internally tracked realized PNL to risk manager for the kill switch
        self.risk_manager.daily_pnl = self.daily_realized_pnl

