        r_low = market_data['rolling_low']
        ema = market_data['ema']
        vwap = market_data['vwap']
        adx = market_data['adx']
        adx_slope = market_data['adx_slope']
        rsi = market_data['rsi']

        if self.in_position:
            self.manage_open_position()
            return

